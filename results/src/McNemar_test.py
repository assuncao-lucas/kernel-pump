algorithms = ["FP$^*$","FP$^{-}$","FP$^{+}$","KP$^*$","KP$^{-}$","KP$^{+}$","KP$^{+/-}$","CPLEX$_{std}$","CPLEX$_{feas}$"]

# -----------------------------
# Step 1: Cochran’s Q test
# -----------------------------
result = sm.stats.cochrans_q(data)
overall = pd.DataFrame([{
    "Comparison": "Cochran’s Q (overall)",
    "Statistic": result.statistic,
    "p-value": result.pvalue,
    "Corrected p-value": "--",
    "Significant": "Yes" if result.pvalue < 0.05 else "No"
}])

# -----------------------------
# Step 2: Pairwise McNemar tests
# -----------------------------
results = []
for (i, j) in combinations(range(len(algorithms)), 2):
    a = data[:, i]
    b = data[:, j]
    both_success = np.sum((a == 1) & (b == 1))
    both_fail    = np.sum((a == 0) & (b == 0))
    a_success_b_fail = np.sum((a == 1) & (b == 0))
    b_success_a_fail = np.sum((a == 0) & (b == 1))
    
    table = [[both_success, b_success_a_fail],
             [a_success_b_fail, both_fail]]
    
    result = mcnemar(table, exact=True)
    results.append({
        "Comparison": f"{algorithms[i]} vs {algorithms[j]}",
        "Statistic": "--",  # McNemar exact test doesn’t return a chi-square statistic
        "p-value": result.pvalue
    })

df = pd.DataFrame(results)

# -----------------------------
# Step 3: Multiple comparison correction
# -----------------------------
reject, pvals_corrected, _, _ = multipletests(df["p-value"], alpha=0.05, method='holm')
df["Corrected p-value"] = pvals_corrected
df["Significant"] = ["Yes" if r else "No" for r in reject]

# Combine overall + pairwise
final_df = pd.concat([overall, df], ignore_index=True)

# -----------------------------
# Step 4: Export to LaTeX
# -----------------------------
latex_table = final_df.to_latex(index=False, float_format="%.3f")
print(latex_table)